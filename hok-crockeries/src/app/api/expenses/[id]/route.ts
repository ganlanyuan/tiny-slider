import { and, eq } from 'drizzle-orm';

import { fail, ok, route } from '@/lib/api';
import { requireCapability } from '@/lib/auth';
import { expenses } from '@/db/schema';
import { logAction } from '@/lib/audit';

export const dynamic = 'force-dynamic';

type Ctx = { params: Promise<{ id: string }> };

export const DELETE = route(async (_request: Request, ctx: Ctx) => {
  const { db, orgId, user } = await requireCapability('expense.manage');
  const { id } = await ctx.params;

  const [expense] = await db
    .select()
    .from(expenses)
    .where(and(eq(expenses.id, id), eq(expenses.orgId, orgId)))
    .limit(1);
  if (!expense) return fail('Expense not found.', 404);

  // Purchase and payroll lines are generated by their source document, so
  // deleting them here would leave the books disagreeing with the ledger.
  if (expense.refType && expense.refType !== 'MANUAL') {
    return fail(
      'This line was created by a stock purchase or a salary payment. Remove the source record instead.',
      409,
    );
  }

  await db.delete(expenses).where(eq(expenses.id, id));
  await logAction(db, user, 'expense.delete', 'expense', id, { amount: expense.amount });
  return ok({ deleted: true });
});
