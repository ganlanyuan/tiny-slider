import { fail, ok, route } from '@/lib/api';
import { requireCapability } from '@/lib/auth';
import { writeDb } from '@/lib/db';
import { logAction } from '@/lib/audit';

export const dynamic = 'force-dynamic';

type Ctx = { params: Promise<{ id: string }> };

export const DELETE = route(async (_request: Request, ctx: Ctx) => {
  const user = await requireCapability('expense.manage');
  const { id } = await ctx.params;

  const result = await writeDb((db) => {
    const expense = db.expenses.find((e) => e.id === id);
    if (!expense) return { ok: false, error: 'Expense not found.', status: 404 } as const;
    // Purchase and payroll lines are generated by their source document, so
    // deleting them here would leave the books disagreeing with the ledger.
    if (expense.refType && expense.refType !== 'MANUAL') {
      return {
        ok: false,
        error: 'This line was created by a stock purchase or a salary payment. Remove the source record instead.',
        status: 409,
      } as const;
    }
    db.expenses = db.expenses.filter((e) => e.id !== id);
    logAction(db, user, 'expense.delete', 'expense', id, { amount: expense.amount });
    return { ok: true } as const;
  });

  if (!result.ok) return fail(result.error, result.status);
  return ok({ deleted: true });
});
