/**
 * Domain vocabulary shared by the server and the browser.
 *
 * The database enums live in `src/db/schema.ts`; this module re-states them as
 * plain constants so client components can import them without pulling the
 * server-only database layer into the browser bundle.
 */

export const ROLES = ['ADMIN', 'MANAGER', 'SR', 'DEALER'] as const;
export type Role = (typeof ROLES)[number];

export const ROLE_LABEL: Record<Role, string> = {
  ADMIN: 'Owner',
  MANAGER: 'Manager',
  SR: 'Sales Rep',
  DEALER: 'Dealer',
};

export const ROLE_DESCRIPTION: Record<Role, string> = {
  ADMIN: 'Full access, including purchase cost and profit.',
  MANAGER: 'Runs the operation. Cannot see purchase cost or profit.',
  SR: 'Sells in the market. Sees only their own stock, invoices and cash.',
  DEALER: 'Read-only catalogue with market prices and availability.',
};

export const SALE_STATUSES = ['PENDING', 'DELIVERED', 'CANCELLED'] as const;
export type SaleStatus = (typeof SALE_STATUSES)[number];

export const SALE_STATUS_LABEL: Record<SaleStatus, string> = {
  PENDING: 'Pending delivery',
  DELIVERED: 'Delivered',
  CANCELLED: 'Cancelled',
};

export const DEMAND_STATUSES = ['PENDING', 'APPROVED', 'FULFILLED', 'REJECTED'] as const;
export type DemandStatus = (typeof DEMAND_STATUSES)[number];

export const DEMAND_STATUS_LABEL: Record<DemandStatus, string> = {
  PENDING: 'Waiting',
  APPROVED: 'Approved',
  FULFILLED: 'Fulfilled',
  REJECTED: 'Rejected',
};

export const PRIORITIES = ['LOW', 'NORMAL', 'HIGH'] as const;
export type Priority = (typeof PRIORITIES)[number];

export const PRIORITY_LABEL: Record<Priority, string> = {
  LOW: 'Low — whenever convenient',
  NORMAL: 'Normal',
  HIGH: 'Urgent — shops are waiting',
};

export const PAYMENT_METHODS = ['CASH', 'BKASH', 'NAGAD', 'ROCKET', 'BANK', 'CARD'] as const;
export type PaymentMethod = (typeof PAYMENT_METHODS)[number];

export const EXPENSE_CATEGORIES = [
  'PRODUCT',
  'SALARY',
  'COMMISSION',
  'TRANSPORT',
  'RENT',
  'UTILITY',
  'MARKETING',
  'MAINTENANCE',
  'OTHER',
] as const;
export type ExpenseCategory = (typeof EXPENSE_CATEGORIES)[number];

export const EXPENSE_LABEL: Record<ExpenseCategory, string> = {
  PRODUCT: 'Product purchase',
  SALARY: 'Salary',
  COMMISSION: 'Commission',
  TRANSPORT: 'Transport',
  RENT: 'Rent',
  UTILITY: 'Utilities',
  MARKETING: 'Marketing',
  MAINTENANCE: 'Maintenance',
  OTHER: 'Other',
};

/** Categories a person can book by hand. The rest are generated by the system. */
export const MANUAL_EXPENSE_CATEGORIES = EXPENSE_CATEGORIES.filter(
  (c) => c !== 'PRODUCT' && c !== 'SALARY' && c !== 'COMMISSION',
);

/* ------------------------------------------------------- wire-level types */

/** A user as sent to the browser. Never carries a password hash. */
export interface SafeUser {
  id: string;
  orgId: string;
  name: string;
  email: string;
  phone: string;
  role: Role;
  active: boolean;
  area: string | null;
  monthlySalary: number;
  commissionRate: number;
  joinedAt: string;
  lastLoginAt: string | null;
  note: string | null;
  createdAt: string;
}

export interface OrgSummary {
  id: string;
  name: string;
  slug: string;
  tagline: string;
  address: string;
  phone: string;
  email: string;
  currency: string;
  lowStockThreshold: number;
  units: string[];
  onboardedAt: string | null;
}

export interface SessionUser {
  user: SafeUser;
  org: OrgSummary;
  capabilities: string[];
}
